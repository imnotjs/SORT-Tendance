"""
SORT-tendance :: src/core/gating_opt.py

Production-grade State Machine Gating Engine.

Responsibilities:
  1. Maintain the global RAM-resident container `attendance_final_log`
     that securely binds active track IDs to verified student records
     or localized stranger classifications.
  2. Enforce Strict State Labeling & Gating Cascades across three
     deterministic states:
       * VERIFIED STUDENT -- live face similarity clears the matching
         threshold (0.60 - 0.65 adaptive). Push the resolved
         "[NRP / Student Name]" label to the bounding box, fire a
         single secure log transaction, flag the track as low-priority,
         and PERMANENTLY suspend all face scanning / extraction /
         Re-ID for that track ID.
       * STRANGER_XX -- person bbox is maintained but face metrics
         continuously fall below the floor (< 0.60). Query the track's
         body-reid vector against Index Instance 2 (Dynamic Appearance
         Cache). If a match clears appearance_inherit_threshold
         (>= 0.65), inherit the existing tracking number. Otherwise
         increment the sequential counter, register the vector, and
         lock the label. Once flagged as a Stranger, ALL facial
         scanning is fully terminated -- reliance shifts purely to
         backend spatial coordinate tracking.
       * ANOMALY -- face elements are detected WITHOUT a corresponding
         body bounding box. Intercept, label strictly as "[ANOMALY]",
         bypass standard tracking logic, and force the throttle
         controller into BURST mode to prevent data loss.
  3. Deterministic BBox Timestamping Layer -- for every transaction,
     extract the exact hardware frame index timestamp at the microsecond
     the bounding box was generated, decoupling logging chronologies
     from processing lag or queue latencies.

Author: SORT-tendance Engineering
"""

