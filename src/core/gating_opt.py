def _self_test() -> None:
    """Lightweight self-test harness (no external engine dependencies)."""
    logging.basicConfig(level=logging.INFO)
    logger.info("=== SORT-tendance gating_opt self-test ===")

    cfg = ConfigRegistry.load("config/config.yaml") if ConfigRegistry else {}
    gate = GatingEngine(config=cfg)
    gate.initialize()

    # --- State 1: VERIFIED STUDENT ---
    ts = gate.make_frame_timestamp(frame_index=1, capture_us=1_700_000_000_000_000)
    state = gate.evaluate_track(
        track_id=10,
        frame_ts=ts,
        bbox=(100, 100, 200, 200),
        centroid=(150.0, 150.0),
        face_similarity=0.72,
        best_student_id="2024001",
        best_student_name="John Doe",
        body_feature=None,
        effective_threshold=0.65,
        ema_score=0.70,
        ema_cluster_size=5,
    )
    logger.info(
        "Track 10 -> state=%s label=%s",
        state.state.value, state.resolved_label,
    )

    # --- State 2: STRANGER ---
    rng = np.random.default_rng(0)
    body_feat = rng.normal(0, 1, size=(512,)).astype(np.float32)
    body_feat /= np.linalg.norm(body_feat)
    ts2 = gate.make_frame_timestamp(frame_index=2, capture_us=1_700_000_000_001_000)
    for _ in range(gate.STRANGER_PENDING_THRESHOLD):
        state2 = gate.evaluate_track(
            track_id=11,
            frame_ts=ts2,
            bbox=(300, 100, 400, 200),
            centroid=(350.0, 150.0),
            face_similarity=0.30,
            best_student_id=None,
            best_student_name=None,
            body_feature=body_feat,
        )
    logger.info(
        "Track 11 -> state=%s label=%s",
        state2.state.value, state2.resolved_label,
    )

    # --- State 3: ANOMALY ---
    ts3 = gate.make_frame_timestamp(frame_index=3, capture_us=1_700_000_000_002_000)
    anomaly = gate.evaluate_anomaly(
        face_bbox=(500, 50, 540, 90),
        frame_ts=ts3,
        body_track_ids=[],
    )
    logger.info(
        "Anomaly -> label=%s frame=%d", anomaly.label, anomaly.timestamp.frame_index,
    )

    telemetry = gate.telemetry()
    logger.info("Telemetry: %s", telemetry)
    gate.shutdown()
    logger.info("=== self-test complete ===")


if __name__ == "__main__":
    _self_test()